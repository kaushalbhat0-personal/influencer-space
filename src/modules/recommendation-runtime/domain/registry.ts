const REGISTRY_BY_ID = new Map(RECOMMENDATION_REGISTRY.map((r) => [r.id, r]));

export function getRecommendation(id: string): RecommendationDefinition | undefined {
  return REGISTRY_BY_ID.get(id);
}

export function isKnownRecommendation(id: string): boolean {
  return REGISTRY_BY_ID.has(id);
}
