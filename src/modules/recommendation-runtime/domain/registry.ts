// ── Recommendation Registry (Phase 1) ──────────────────────
// One canonical registry of recommendations. Every entry declares its
// trigger, its completion condition, its expected impact, its goal affinity,
// its knowledge/success dependencies, and its actions. The engine, categories,
// dashboard, builder, history and analytics ALL derive from this registry.
//
// Everything is a pure predicate over the RecommendationContext — the runtime
// never owns data and never invents recommendations.

import { getField } from "@/modules/knowledge-runtime";
import type { RecommendationContext, RecommendationDefinition } from "./types";

const fieldComplete = (ctx: RecommendationContext, fieldId: string): boolean =>
  getField(fieldId)?.complete(ctx.snapshot) ?? false;

const goalActive = (ctx: RecommendationContext, goalId: string): boolean =>
  ctx.activeProfile?.weights.some((w) => w.goalId === goalId && w.weight > 0) ?? false;

const declaredTruthy = (ctx: RecommendationContext, key: string): boolean =>
  ctx.snapshot.declared[key] === true ||
  (typeof ctx.snapshot.declared[key] === "string" && ctx.snapshot.declared[key].trim().length > 0);

