// One canonical registry. Every field the runtime can score, detect, ask
// about, and complete is declared here. The score engine, missing-field
// analyzer, question engine, builder hints, and storefront score ALL derive
// from this registry — nothing is hard-coded in a UI or a service.

import type { KnowledgeField } from "./types";

const hasText = (value: unknown): boolean => typeof value === "string" && value.trim().length > 0;
const minCount = (value: unknown, min: number): boolean =>
  Array.isArray(value) && value.length >= min;

const ratioComplete = (present: number, total: number, target = 3): boolean =>
  total === 0 || present >= Math.min(target, total);

