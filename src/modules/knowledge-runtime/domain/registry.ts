export function getField(fieldId: string): KnowledgeField | undefined {
  return KNOWLEDGE_REGISTRY.find((f) => f.id === fieldId);
}

export function getFieldByDeclaredKey(key: string): KnowledgeField | undefined {
  return KNOWLEDGE_REGISTRY.find((f) => f.source === "declared" && declaredKeyFor(f.id) === key);
}

/** Maps a field id to its `knowledge_completion` fact key. */
export function declaredKeyFor(fieldId: string): string {
  return fieldId.replace(/\./g, "_");
}
